let lang = 'ar';

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = STRINGS[next] ? next : 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  }
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
}

export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export function formatNumber(n) {
  return new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-US').format(n);
}

export function formatBytes(bytes) {
  if (!bytes) return '';
  const units = ['B', 'KB', 'MB', 'GB'];
  let i = 0;
  let v = bytes;
  while (v >= 1024 && i < units.length - 1) { v /= 1024; i++; }
  return `${v.toFixed(v >= 100 || i === 0 ? 0 : 1)} ${units[i]}`;
}

export function timeAgo(ts) {
  if (!ts) return '';
  const s = Math.max(0, (Date.now() - ts) / 1000);
  if (s < 60) return t('justNow');
  if (s < 3600) return t('minutesAgo', { n: Math.round(s / 60) });
  if (s < 86400) return t('hoursAgo', { n: Math.round(s / 3600) });
  return t('daysAgo', { n: Math.round(s / 86400) });
}

export function formatDuration(ms) {
  const m = Math.max(1, Math.round(ms / 60000));
  const n = formatNumber;
  if (m < 60) return lang === 'ar' ? `${n(m)} د` : `${m} min`;
  const h = Math.floor(m / 60);
  return lang === 'ar' ? `${n(h)} س ${n(m % 60)} د` : `${h} h ${m % 60} min`;
}
